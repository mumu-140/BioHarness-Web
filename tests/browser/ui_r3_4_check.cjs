// Real-browser Chromium acceptance for R3.4:
// Professional Scientific Modules (Literature, Statistics report_binding render & drift verify,
// Scientific Review non-blocking disclosure, Protein Methods real structure-inventory CLI,
// non-runnable dapseq/genome-web-tf/sequence honest boundaries, Executions domain renderer,
// and 390/320px responsive check).
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');

const BASE = process.env.BASE;
const TOKEN = process.env.TOKEN;
const OUT = '/qa/out';

const results = [];
const check = (name, ok, detail = '') => results.push({ name, ok: !!ok, detail: String(detail) });

(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] });
  const context = await browser.newContext({
    viewport: { width: 1440, height: 900 },
    locale: 'zh-CN',
  });
  await context.addInitScript(() => {
    window.localStorage.setItem('lang', 'zh-Hans');
  });
  const page = await context.newPage();

  const pageErrors = [];
  const cspViolations = [];
  const externalReqs = [];
  const origin = new URL(BASE).origin;

  page.on('pageerror', (e) => pageErrors.push(e.message));
  page.on('console', (m) => {
    const t = m.text();
    if (t.includes('Content Security Policy') || t.includes('violates the following Content Security Policy')) {
      cspViolations.push(t);
    }
  });
  page.on('request', (req) => {
    const u = req.url();
    if (u.startsWith('data:') || u.startsWith('blob:') || u.startsWith('about:')) return;
    if (!u.startsWith(origin)) externalReqs.push(u);
  });

  try {
    // 1. Login and navigate to Domain Modules subtab
    await page.goto(BASE + '/');
    await page.locator('#password').fill(TOKEN);
    await page.getByTestId('login-button').click();
    await page.getByTestId('bh-sidebar').waitFor({ timeout: 20000 });

    await page.getByTestId('bh-sidebar-capabilities-btn').click();
    await page.getByTestId('bh-cap-subtab-modules').click();
    await page.getByTestId('bh-cap-modules-panel').waitFor({ timeout: 15000 });
    await page.getByTestId('bh-domain-mod-statistics').waitFor({ timeout: 20000 });

    // Check honest non-runnable module disclosures
    const nonRunText = await page.getByTestId('bh-domain-nonrunnable-section').innerText();
    const pqaBadge = await page.getByTestId('bh-lit-provider-paperqa2').innerText();
    check('Non-runnable modules (dapseq/genome-web-tf/sequence) & paperqa2 honestly disclosed',
      nonRunText.includes('DAP-seq') &&
        nonRunText.includes('Genome-web TF') &&
        nonRunText.includes('Sequence') &&
        pqaBadge.includes('NOT_PRODUCTION_ENABLED'),
      `${pqaBadge} | ${nonRunText.slice(0, 140)}`);

    // 2. Literature: inspect real search.json generated by bioharness-literature, check coverage & pagination
    await page.getByTestId('bh-lit-file-select').selectOption('search.json');
    await page.getByTestId('bh-lit-inspect-btn').click();
    await page.getByTestId('bh-domain-literature-card').waitFor({ timeout: 15000 });

    const covText = await page.getByTestId('bh-lit-coverage-badge').innerText();
    const page1Info = await page.getByTestId('bh-lit-page-info').innerText();
    check('Literature artifact renders coverage boundary and page 1 (1–10 of 12)',
      covText.includes('ranked_subset_not_exhaustive') && page1Info.includes('1–10'),
      `${covText} | ${page1Info}`);

    await page.getByTestId('bh-lit-next-btn').click();
    await page.waitForFunction(() => {
      const el = document.querySelector('[data-testid="bh-lit-page-info"]');
      return el && el.textContent.includes('11–12');
    }, { timeout: 10000 });
    check('Literature pagination advances cleanly to page 2 (11–12)', true);

    // 3. Statistics: deterministic render PASS, then verify FAIL on tampered report
    await page.getByTestId('bh-stat-action-select').selectOption('render');
    await page.getByTestId('bh-stat-records-select').selectOption('stats_bundle.json');
    await page.getByTestId('bh-stat-template-select').selectOption('answer.template.md');
    await page.getByTestId('bh-stat-run-btn').click();
    await page.getByTestId('bh-domain-statistics-card').waitFor({ timeout: 15000 });

    const statBadge = await page.getByTestId('bh-stat-status-badge').innerText();
    const statRow = await page.getByTestId('bh-stat-row-mut_rate').innerText();
    const statOr = await page.getByTestId('bh-stat-row-de_or').innerText();
    const statMd = await page.getByTestId('bh-stat-rendered-md').innerText();
    check('Statistics report_binding render PASSES and shows verbatim numerator/denominator, CI, p & FDR',
      statBadge.includes('PASS') &&
        statRow.includes('6 / 40') &&
        statOr.includes('p=0.004') &&
        statOr.includes('FDR=0.018') &&
        statMd.includes('15.0%(6/40)'),
      `${statBadge} | ${statMd}`);

    await page.getByTestId('bh-stat-action-select').selectOption('verify');
    await page.getByTestId('bh-stat-report-select').selectOption('answer_drifted.txt');
    await page.getByTestId('bh-stat-run-btn').click();
    await page.getByTestId('bh-stat-binding-error').waitFor({ timeout: 15000 });
    const driftErr = await page.getByTestId('bh-stat-binding-error').innerText();
    check('Statistics report_binding verify catches tampered number with REPORT_BINDING_FAIL',
      driftErr.includes('REPORT_BINDING_FAIL'), driftErr);

    // 4. Scientific Review honest version & CodeArtsIntakeReviewer direct-API gap disclosure
    const revGap = await page.getByTestId('bh-review-api-gap-note').innerText();
    check('Scientific Review discloses CodeArtsIntakeReviewer direct model API gap honestly',
      revGap.includes('CodeArtsIntakeReviewer') && revGap.includes('BioHarness-Modules'),
      revGap);

    // 5. Protein Methods: run real bioharness-protein-methods structure-inventory on helix.pdb
    await page.getByTestId('bh-protein-op-select').selectOption('structure-inventory');
    await page.getByTestId('bh-protein-input-select').selectOption('helix.pdb');
    await page.getByTestId('bh-protein-run-btn').click();
    await page.getByTestId('bh-domain-protein-card').waitFor({ timeout: 15000 });

    const resCount = await page.getByTestId('bh-protein-residue-count').innerText();
    const atomCount = await page.getByTestId('bh-protein-atom-count').innerText();
    check('Protein Methods real structure-inventory returns residue=1, atom=4',
      resCount.trim() === '1' && atomCount.trim() === '4',
      `residues=${resCount}, atoms=${atomCount}`);

    // 6. Execution Inspector auto-renders domain summary card for recorded module tool output
    await page.getByTestId('bh-tab-executions').click();
    await page.getByTestId('bh-executions-route').waitFor({ timeout: 15000 });
    const firstConvBtn = page.locator('[data-testid="bh-conversations-list"] button').first();
    if (await firstConvBtn.count()) {
      await firstConvBtn.click();
      await page.getByTestId('bh-tab-executions').click();
    }
    await page.getByTestId('bh-executions-list').waitFor({ timeout: 15000 });
    await page.locator('[data-testid^="bh-exec-row-"]').first().click();
    await page.getByTestId('bh-execution-detail').waitFor({ timeout: 15000 });
    const execDomainCard = await page.getByTestId('bh-domain-protein-card').count();
    check('Execution detail auto-renders domain card above collapsed Technical Details',
      execDomainCard === 1, `cards=${execDomainCard}`);

    // 7. Responsive check at 390px and 320px on /w/capabilities?tab=modules
    await page.goto(BASE + '/w/capabilities?ws=primary&tab=modules');
    await page.getByTestId('bh-cap-modules-panel').waitFor({ timeout: 15000 });
    for (const vp of [{ width: 390, height: 844 }, { width: 320, height: 640 }]) {
      await page.setViewportSize(vp);
      await page.waitForTimeout(250);
      const overflow = await page.evaluate(() => ({
        scroll: document.documentElement.scrollWidth,
        client: document.documentElement.clientWidth,
      }));
      check(`No horizontal overflow on Domain Modules at ${vp.width}px`,
        overflow.scroll <= overflow.client + 2, JSON.stringify(overflow));
    }

    check('Zero uncaught page errors', pageErrors.length === 0, pageErrors.join('; '));
    check('Zero CSP violations', cspViolations.length === 0, cspViolations.join('; '));
    check('Zero external network requests', externalReqs.length === 0, externalReqs.join('; '));
  } catch (err) {
    check('Unhandled R3.4 browser error', false, err && err.stack ? err.stack : String(err));
  } finally {
    await browser.close();
  }

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(`${OUT}/results.json`, JSON.stringify(results, null, 2));
  process.exit(results.every((r) => r.ok) ? 0 : 1);
})();
